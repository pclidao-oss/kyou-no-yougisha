CREATE TABLE IF NOT EXISTS devices (id TEXT PRIMARY KEY, first_day TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS devices_cohort ON devices(first_day);
CREATE TABLE IF NOT EXISTS visits (device TEXT NOT NULL, day TEXT NOT NULL, PRIMARY KEY(device,day));
CREATE INDEX IF NOT EXISTS visits_day ON visits(day,device);
CREATE TABLE IF NOT EXISTS plays (device TEXT NOT NULL, day TEXT NOT NULL, started INTEGER NOT NULL DEFAULT 0, seconds INTEGER, shares INTEGER NOT NULL DEFAULT 0, PRIMARY KEY(device,day));
CREATE INDEX IF NOT EXISTS plays_day ON plays(day,seconds);
CREATE TABLE IF NOT EXISTS counters (day TEXT PRIMARY KEY, writes INTEGER NOT NULL DEFAULT 0);

CREATE TABLE IF NOT EXISTS insight_visits (
 id TEXT PRIMARY KEY,device TEXT NOT NULL,day TEXT NOT NULL,hour INTEGER NOT NULL,
 source TEXT NOT NULL,screen TEXT NOT NULL,browser TEXT NOT NULL,language TEXT NOT NULL,country TEXT NOT NULL,
 created INTEGER NOT NULL,updated INTEGER NOT NULL,started INTEGER NOT NULL DEFAULT 0,cleared INTEGER NOT NULL DEFAULT 0,
 seconds INTEGER,shares INTEGER NOT NULL DEFAULT 0,progress INTEGER NOT NULL DEFAULT 1,
 hints INTEGER NOT NULL DEFAULT 0,mistakes INTEGER NOT NULL DEFAULT 0,active INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS insight_visit_day ON insight_visits(day,source);
CREATE INDEX IF NOT EXISTS insight_visit_device ON insight_visits(device,day);
CREATE TABLE IF NOT EXISTS insight_meta(key TEXT PRIMARY KEY,value INTEGER NOT NULL);
